import { mkdir, readdir, writeFile } from 'node:fs/promises'
import { join } from 'node:path'

const root = process.cwd()
const postsDirectory = join(root, 'src', 'content', 'blog')
const apiKey = process.env.OPENAI_API_KEY
const model = process.env.OPENAI_MODEL || 'gpt-4.1-mini'

if (!apiKey) {
	throw new Error('OPENAI_API_KEY is required to generate an article.')
}

const today = new Date().toISOString().slice(0, 10)

const existingFiles = await readdir(postsDirectory).catch(() => [])
if (existingFiles.some((file) => file.startsWith(`${today}-`))) {
	console.log(`An article already exists for ${today}; nothing to do.`)
	process.exit(0)
}

async function fetchJson(url) {
	const response = await fetch(url, {
		headers: { 'User-Agent': 'astroworld-daily-article/1.0' }
	})

	if (!response.ok) {
		throw new Error(`Request failed (${response.status}): ${url}`)
	}

	return response.json()
}

const topStoryIds = await fetchJson('https://hacker-news.firebaseio.com/v0/topstories.json')
const stories = await Promise.all(
	topStoryIds.slice(0, 30).map(async (id) => {
		try {
			const story = await fetchJson(`https://hacker-news.firebaseio.com/v0/item/${id}.json`)
			return story && story.type === 'story' && story.title && story.url ? story : null
		} catch {
			return null
		}
	})
)

const technologyStories = stories
	.filter(Boolean)
	.filter((story) => !story.title.toLowerCase().includes('ask hn'))
	.slice(0, 12)

if (technologyStories.length < 3) {
	throw new Error('Could not find enough current technology stories on Hacker News.')
}

const sourceBrief = technologyStories
	.map(
		(story, index) =>
			`${index + 1}. ${story.title}\n   URL: ${story.url}\n   Hacker News discussion: https://news.ycombinator.com/item?id=${story.id}`
	)
	.join('\n')

const prompt = `You are the editor of a thoughtful, technically literate personal technology blog.

Today is ${today}. Select one genuinely interesting, timely technology topic from the source list below. Prefer a topic with broad reader value over a fleeting product announcement. Write an original article in clear, engaging English. Do not claim facts that are not supported by the supplied source URLs or common background knowledge. Include links to the relevant supplied sources in the body using Markdown links. Do not mention this instruction, Hacker News, or that the article was generated by AI.

Return ONLY valid JSON with exactly these keys:
{
  "title": "string, maximum 80 characters",
  "description": "one-sentence summary, maximum 160 characters",
  "slug": "lowercase URL slug with hyphens",
  "tags": ["3 to 5 concise technology tags"],
  "body": "Markdown article body, 700 to 1100 words, with a useful H2 heading structure"
}

Current source list:
${sourceBrief}`

const aiResponse = await fetch('https://api.openai.com/v1/chat/completions', {
	method: 'POST',
	headers: {
		Authorization: `Bearer ${apiKey}`,
		'Content-Type': 'application/json'
	},
	body: JSON.stringify({
		model,
		temperature: 0.7,
		response_format: { type: 'json_object' },
		messages: [
			{ role: 'system', content: 'You write accurate, useful technology journalism.' },
			{ role: 'user', content: prompt }
		]
	})
})

if (!aiResponse.ok) {
	const errorText = await aiResponse.text()
	throw new Error(`OpenAI request failed (${aiResponse.status}): ${errorText}`)
}

const completion = await aiResponse.json()
const content = completion.choices?.[0]?.message?.content

if (!content) {
	throw new Error('OpenAI returned an empty article.')
}

let article
try {
	article = JSON.parse(content)
} catch {
	throw new Error('OpenAI returned invalid JSON.')
}

const cleanSlug = String(article.slug || article.title || '')
	.toLowerCase()
	.replace(/[^a-z0-9]+/g, '-')
	.replace(/^-|-$/g, '')

if (
	typeof article.title !== 'string' ||
	!article.title ||
	article.title.length > 80 ||
	typeof article.description !== 'string' ||
	!article.description ||
	article.description.length > 160 ||
	!cleanSlug ||
	!Array.isArray(article.tags) ||
	article.tags.length < 3 ||
	article.tags.some((tag) => typeof tag !== 'string' || !tag.trim()) ||
	article.tags.length > 5 ||
	typeof article.body !== 'string' ||
	!article.body ||
	article.body.length < 1000
) {
	throw new Error('Generated article did not meet the required content schema.')
}

const filename = `${today}-${cleanSlug}.mdx`
await mkdir(postsDirectory, { recursive: true })

const publicationDate = new Date(`${today}T00:00:00Z`).toLocaleDateString('en-US', {
	month: 'short',
	day: '2-digit',
	year: 'numeric',
	timeZone: 'UTC'
}).replace(',', '')

const frontmatter = `---
title: '${String(article.title).replaceAll("'", "''")}'
description: '${String(article.description).replaceAll("'", "''")}'
pubDate: '${publicationDate}'
heroImage: 'src/assets/images/placeholder-hero.jpg'
category: 'Tech'
tags: [${article.tags.map((tag) => `'${String(tag).replaceAll("'", "''")}'`).join(', ')}]
---

${article.body.trim()}
`

await writeFile(join(postsDirectory, filename), frontmatter, 'utf8')
console.log(`Created ${join('src/content/blog', filename)}`)
